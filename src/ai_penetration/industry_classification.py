def classify_industry(code: str) -> str:
    """将 GB/T 4754 编码归类到大类层面（门类字母 + 大类名）。

    Args:
        code: ent 表 industry_code，如 "C221" / "C22" / "C" / ""。

    Returns:
        大类标签，如 "C22造纸和纸制品业"；仅门类时返回 "C制造业"；
        空值或无法识别时返回 "未知"。
    """
    code = (code or "").strip()
    if not code:
        return "未知"
    section = code[0].upper()
    if not section.isalpha() or len(code) < 2 or not code[1:3].isdigit():
        # 非标准编码，回退到门类名或未知
        name = SECTIONS.get(section)
        return f"{section}{name}" if name else "未知"
    major_key = (section, code[1:3])
    major_name = MAJOR_CLASSES.get(major_key)
    if major_name:
        return f"{section}{major_key[1]}{major_name}"
    # 大类未收录（如过期编码），回退门类
    section_name = SECTIONS.get(section)
    return f"{section}{section_name}" if section_name else "未知"
